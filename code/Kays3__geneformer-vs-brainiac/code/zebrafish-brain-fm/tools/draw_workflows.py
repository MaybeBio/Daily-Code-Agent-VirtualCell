"""Draw every workflow from its code and write WORKFLOWS.md.

Each workflow script has a build() function that makes the Neuro-Workflow graph
without running it. This tool calls build(), reads the nodes and connections of
the graph, and writes one mermaid diagram per workflow. The pictures therefore
cannot differ from the code. Run from the zebrafish-brain-fm folder:

    uv run python tools/draw_workflows.py            # rewrite WORKFLOWS.md
    uv run python tools/draw_workflows.py --check    # fail if WORKFLOWS.md is out of date
"""

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "workflows"))

# (script, arguments passed to build, note under the title)
WORKFLOWS = [
    ("stage0_inventory.py", [], ""),
    ("tier_s_smoke.py", [], "The tier M timing run (`tier_m_timing.py`) has the same graph with a larger model."),
    ("stage1_retina_tier_s.py", [], ""),
    ("stage1b_retina_external.py", ["--with-scgpt"], "Drawn with `--with-scgpt`. Without it the scGPT node and its probe are absent."),
]


def load(script):
    spec = importlib.util.spec_from_file_location(script[:-3], ROOT / "workflows" / script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def draw(builder):
    lines = ["flowchart TD"]
    for name, node in builder.nodes.items():
        definition = node.NODE_DEFINITION
        label = name if name == type(node).__name__ else f"{name}<br/>{type(node).__name__}"
        lines.append(f'    {name}["{label}<br/>stage: {definition.stage}"]')
    for c in builder.connections:
        port = c.from_port if c.from_port == c.to_port else f"{c.from_port} to {c.to_port}"
        lines.append(f'    {c.from_node} -->|"{port}"| {c.to_node}')
    return "\n".join(lines)


def render():
    parts = ["# Workflows, drawn from the code", "",
             "Generated by `tools/draw_workflows.py`. Do not edit by hand: change the workflow script and run the tool again.",
             "",
             "Each box is a node: its name in the workflow, its class where the two differ, and its Neuro-Workflow stage. "
             "Each arrow is a connection between two ports and carries the port name. "
             "The stage `training` is this project's proposal and is not in the Neuro-Workflow stage list.", ""]
    for script, argv, note in WORKFLOWS:
        module = load(script)
        builder, _ = module.build(argv)
        kinds = sorted({type(node).__name__ for node in builder.nodes.values()})
        parts += [f"## {module.TITLE}", "",
                  f"`workflows/{script}`: {len(builder.nodes)} nodes of {len(kinds)} kinds, {len(builder.connections)} connection{"" if len(builder.connections) == 1 else "s"}.",
                  *([note] if note else []), "", "```mermaid", draw(builder), "```", ""]
    return "\n".join(parts)


if __name__ == "__main__":
    text, target = render(), ROOT / "WORKFLOWS.md"
    if "--check" in sys.argv:
        if not target.is_file() or target.read_text() != text:
            sys.exit("WORKFLOWS.md is out of date: run tools/draw_workflows.py")
        print("WORKFLOWS.md matches the code")
    else:
        target.write_text(text)
        print(f"wrote {target.name}")
